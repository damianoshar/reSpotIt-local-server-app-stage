#!/bin/bash
# start-full-stack.sh — Generate secrets, configure .env, and launch the full stack.
# Usage: ./start-full-stack.sh
set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR"

# ── Generate secrets ──────────────────────────────────────────────────────────
generate_secret() { python3 -c "import secrets; print(secrets.token_hex(32))"; }
generate_token()  { python3 -c "import secrets; print(secrets.token_urlsafe(24))"; }

WEBUI_SECRET_KEY="$(generate_secret)"
MCP_API_KEY="$(generate_token)"
RESPOTIT_MCP_TOKEN="$(generate_token)"
RESPOTIT_MCP_PASSWORD="$(generate_token)"
KEYCLOAK_ADMIN_PASSWORD="$(generate_token)"
KEYCLOAK_DB_PASSWORD="$(generate_token)"
OAUTH_CLIENT_SECRET="$(generate_token)"
OPENWEBUI_DB_PASSWORD="$(generate_token)"
WEBUI_SECRET_KEY_VAL="$WEBUI_SECRET_KEY"

# ── Write .env ────────────────────────────────────────────────────────────────
cat > .env <<EOF
# reSpotIt local server (auto-generated by start-full-stack.sh)
REDIRECT_URI=https://127.0.0.1:8000/api/v1/auth/callback
PUBLIC_BASE_URL=https://127.0.0.1:8000
SSL_ENABLED=true
CORS_ALLOW_ORIGIN=*
FORWARDED_ALLOW_IPS=*

# Spotify (fill in manually)
SPOTIFY_CLIENT_ID=
SPOTIFY_CLIENT_SECRET=

# Keycloak / OpenWebUI OIDC
KEYCLOAK_REALM=open-webui
KEYCLOAK_ADMIN=admin
KEYCLOAK_ADMIN_PASSWORD=$KEYCLOAK_ADMIN_PASSWORD
KEYCLOAK_DB_USER=keycloak
KEYCLOAK_DB_PASSWORD=$KEYCLOAK_DB_PASSWORD
KEYCLOAK_HOSTNAME=https://localhost/authKeycloak
OPENID_PROVIDER_URL=https://localhost/authKeycloak/realms/open-webui/.well-known/openid-configuration
OPENID_REDIRECT_URI=https://localhost/oauth/oidc/callback
OAUTH_PROVIDER_NAME=Keycloak
OAUTH_SCOPES=openid email profile
OAUTH_CLIENT_ID=open-webui
OAUTH_CLIENT_SECRET=$OAUTH_CLIENT_SECRET
OAUTH_AUTO_SIGNUP=true
OAUTH_MERGE_ACCOUNTS_BY_EMAIL=true
ENABLE_OAUTH_SIGNUP=true

# OpenWebUI database
OPENWEBUI_DB_USER=openwebui
OPENWEBUI_DB_PASSWORD=$OPENWEBUI_DB_PASSWORD
OPENWEBUI_DB_NAME=openwebui
WEBUI_AUTH=true
DEFAULT_USER_ROLE=user
WEBUI_SECRET_KEY=$WEBUI_SECRET_KEY

# Spotify MCP
SPOTIFY_CLIENT_ID=
MCP_API_KEY=$MCP_API_KEY

# reSpotIt MCP service account
RESPOTIT_MCP_EMAIL=mcp-service@respotit.local
RESPOTIT_MCP_PASSWORD=$RESPOTIT_MCP_PASSWORD
RESPOTIT_MCP_USER_ID=
RESPOTIT_MCP_API_URL=https://api:8000
RESPOTIT_MCP_API_VERIFY_TLS=false
RESPOTIT_MCP_TOKEN=$RESPOTIT_MCP_TOKEN

# OpenWebUI integration
WEBUI_AUTH_TRUSTED_EMAIL_HEADER=X-OWUI-Trusted-Email
WEBUI_AUTH_TRUSTED_NAME_HEADER=X-OWUI-Trusted-Name
OPENWEBUI_TRUSTED_AUTH=true
OPENWEBUI_URL=http://open-webui:8080

# External model endpoint (llama-server)
OPENAI_API_BASE_URL=http://host.docker.internal:8080/v1
OPENAI_API_KEY=local

# Telemetry
SCARF_NO_ANALYTICS=true
DO_NOT_TRACK=true
ANONYMIZED_TELEMETRY=false
EOF

echo "✅ .env generated with random secrets."

# ── Copy required files from backup workspace ─────────────────────────────────
BACKUP_DIR="../reSpotIt-local-server-app-clean-backup-2"
if [ -d "$BACKUP_DIR/certs" ]; then
    cp -r "$BACKUP_DIR/certs" . 2>/dev/null || true
    echo "✅ Copied certs/"
fi
if [ -d "$BACKUP_DIR/OpenWebUI-stack" ]; then
    cp -r "$BACKUP_DIR/OpenWebUI-stack" . 2>/dev/null || true
    echo "✅ Copied OpenWebUI-stack/"
fi

# ── Launch full stack ─────────────────────────────────────────────────────────
echo "🚀 Starting full stack..."
docker compose -f docker-compose.yml -f docker-compose.full.yml up -d --build

echo ""
echo "✅ Full stack started!"
echo "   reSpotIt frontend: http://localhost:8888"
echo "   reSpotIt API:      https://localhost:8000"
echo "   OpenWebUI:         https://localhost/owui/"
echo "   Keycloak Admin:    https://localhost/authKeycloak/admin/"
echo "   MinIO Console:     http://localhost:9001"
echo "   Redis Insight:     http://localhost:5540"